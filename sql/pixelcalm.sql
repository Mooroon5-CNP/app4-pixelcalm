-- À installer par un administrateur dans une base PostgreSQL dédiée et vide.
-- L'application runtime ne crée ni table ni rôle au démarrage.
CREATE TABLE IF NOT EXISTS public.pensees (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  texte text NOT NULL CHECK (length(texte) BETWEEN 1 AND 280),
  saved_at timestamp without time zone NOT NULL DEFAULT timezone('UTC', now())
);
